def _https_origins(environment_variable, default=''):
    origins = []
    for origin in os.getenv(environment_variable, default).split(','):
        origin = origin.strip().rstrip('/')
        if origin and not origin.startswith(('http://', 'https://')):
            origin = f'https://{origin}'
        if origin:
            origins.append(origin)
    return origins

